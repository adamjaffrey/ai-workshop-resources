const {chromium} = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
import assert from 'node:assert/strict';
import {mkdtemp} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
const profile=await mkdtemp(join(tmpdir(),'workshop-browser-'));
const options={headless:true,channel:'chrome',viewport:{width:1440,height:1000}};
let context=await chromium.launchPersistentContext(profile,options);
let page=await context.newPage();const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:8787/');
assert.equal(await page.locator('#workshop-content').count(),0);
await page.screenshot({path:'/tmp/workshop-secure-login.png',fullPage:true});
await page.locator('#workshop-password').fill('wrong-password');await page.getByRole('button',{name:'Unlock resources'}).click();
await page.getByText('That password isn’t correct. Please try again.').waitFor();
await page.locator('#workshop-password').fill('test-only-long-workshop-password');await page.getByRole('button',{name:'Unlock resources'}).click();
await page.getByText('Access granted').waitFor();
await page.locator('#workshop-content').waitFor();
const cookies=await context.cookies();const cookie=cookies.find(c=>c.name==='__Host-workshop_session');
assert.ok(cookie&&cookie.httpOnly&&cookie.secure&&cookie.expires>Date.now()/1000+6.99*86400);
await page.locator('[data-agent="claude-code"]').click();assert.equal(await page.locator('[data-agent="claude-code"]').getAttribute('aria-pressed'),'true');
await page.locator('[data-agent="codex"]').click();
await page.screenshot({path:'/tmp/workshop-secure-resources.png',fullPage:true});
const tab=await context.newPage();await tab.goto('http://127.0.0.1:8787/');assert.equal(await tab.locator('#workshop-content').count(),1);await tab.close();
await context.close();
context=await chromium.launchPersistentContext(profile,options);page=await context.newPage();await page.goto('http://127.0.0.1:8787/');
assert.equal(await page.locator('#workshop-content').count(),1);
await page.getByRole('button',{name:'Log out',exact:true}).click();await page.locator('#workshop-password').waitFor();
assert.equal(await page.locator('#workshop-content').count(),0);
await page.setViewportSize({width:390,height:844});await page.screenshot({path:'/tmp/workshop-secure-mobile.png',fullPage:true});
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
assert.deepEqual(errors,[]);await context.close();
console.log('PASS: hidden-content absence; wrong-password feedback; correct login; cookie flags and seven-day lifetime; agent toggle; new tab; browser restart; logout; mobile overflow; no page errors');
